#!/bin/sh
# Online-menu entry point. Payload is verified before changing the app volume.
set -u
umask 077
ACTION=${1:-status}
shift || exit 1
PREFIX=
FIXTURE=0
if [ "${1:-}" = --fixture-root ]; then
    PREFIX=${2:?Missing fixture directory}
    [ "$(uname -s)" = Linux ] && [ -f "$PREFIX/.cw-fixture" ] || exit 1
    FIXTURE=1
elif [ "${1:-}" = --mmx-child ]; then
    shift
elif [ -r /net/mmx/ifs/lsd.jxe ]; then
    command -v on >/dev/null 2>&1 || { echo "ERROR: MMX dispatch unavailable"; exit 1; }
    SCRIPT=$0
    case "$SCRIPT" in /net/mmx/*) SCRIPT=${SCRIPT#/net/mmx};; esac
    exec on -f mmx /bin/sh "$SCRIPT" "$ACTION" --mmx-child
elif [ ! -r /ifs/lsd.jxe ]; then
    echo "ERROR: Porsche MMX filesystem unavailable"; exit 1
fi
APP="$PREFIX/mnt/app"
ROOT="$APP/eso/hmi/connectwow-carplay"
DIO="$APP/eso/bin/apps/dio_manager"
PAYLOAD=
for SD in "$PREFIX/fs/sda0" "$PREFIX/fs/sdb0"; do
    if [ -s "$SD/online/carplay/payload.manifest" ]; then PAYLOAD="$SD/online/carplay"; break; fi
done
fail() { echo "ERROR: $*"; exit 1; }
rw() { [ "$FIXTURE" -eq 1 ] || mount -uw "$APP"; }
ro() { [ "$FIXTURE" -eq 1 ] || mount -ur "$APP"; }
read_text() { [ ! -r "$1" ] || while IFS= read -r LINE; do echo "$LINE"; done < "$1"; }
cw_sha256() { "$TOOL" --hash "$1"; }
verify() {
    BASE=$1
    [ "$(cw_sha256 "$BASE/payload.manifest")" = '@MANIFEST_SHA256@' ] || return 1
    while IFS=' ' read -r EXPECTED NAME; do
        case "$NAME" in porsche-carplay|libcw-porsche-capture_receiver.so|libcw-porsche-rgi.so|libcw-query-stdio.so|dio_manager.sh) ;;
            *) return 1;; esac
        [ "$(cw_sha256 "$BASE/$NAME")" = "$EXPECTED" ] || return 1
    done < "$BASE/payload.manifest"
}
case "$ACTION" in
status)
    if [ ! -s "$ROOT/installed.manifest" ]; then echo "Not installed"; exit 0; fi
    echo "ConnectWow native CarPlay / Porsche K5137 MU1417 (original HMI)"
    if [ -e "$ROOT/enabled" ]; then echo "Selected: CarPlay map (when available)"; else echo "Selected: original Porsche map"; fi
    echo "Current geometry:"; read_text "$PREFIX/ramdisk/cw-carplay-geometry.v3"
    echo "Validated video output:"; read_text "$PREFIX/ramdisk/cw-carplay-ready.v1"
    echo "Supervisor:"; read_text "$PREFIX/ramdisk/cw-porsche-carplay.log"
    echo "No video lease means the original map remains selected."
    exit 0;;
enable|disable)
    [ -s "$ROOT/installed.manifest" ] || fail "Install first"
    rw || fail "App volume unavailable"
    if [ "$ACTION" = enable ]; then : > "$ROOT/enabled" || { ro; fail "Cannot enable"; }
    else rm -f "$ROOT/enabled" || { ro; fail "Cannot disable"; }; fi
    ro || fail "Cannot remount app read-only"
    echo "Map selection changed. Central CarPlay remains available."
    exit 0;;
install|restore) ;;
*) fail "Unknown action";;
esac
[ -n "$PAYLOAD" ] || fail "Extract the CarPlay overlay on the SD card first"
TOOL="$PAYLOAD/porsche-carplay"
[ -x "$TOOL" ] || fail "Native verifier missing or not executable"
# Generated by the package builder; do not accept a different verifier.
[ "$(cw_sha256 "$TOOL")" = '@VERIFIER_SHA256@' ] || fail "Wrong native verifier"
verify "$PAYLOAD" || fail "Payload damaged or unreadable"
if [ "$ACTION" = restore ]; then
    [ -s "$ROOT/installed.manifest" ] || fail "No installation to restore"
    [ "$(cw_sha256 "$DIO")" = "$(cw_sha256 "$ROOT/dio_manager.sh")" ] || fail "DIO changed externally; refusing to overwrite"
    [ "$(cw_sha256 "$DIO.cw-stock")" = "$(cw_sha256 "$ROOT/backup/dio_manager")" ] || fail "DIO backup differs"
    rw || fail "App volume unavailable"
    # Remove enable flag first; the running supervisor restores the OEM context.
    rm -f "$ROOT/enabled" || { ro; fail "Cannot disable"; }
    cp -p "$ROOT/backup/dio_manager" "$DIO.cw-restore" || { ro; fail "Cannot stage restoration"; }
    mv -f "$DIO.cw-restore" "$DIO" || { ro; fail "Restore incomplete; backups retained"; }
    rm -f "$ROOT/installed.manifest"
    ro || fail "Cannot remount app read-only"
    echo "Original DIO launcher restored. HMI was never modified. Restart PCM."
    exit 0
fi
if [ -s "$ROOT/installed.manifest" ]; then
    verify "$ROOT" || fail "Installed payload differs; restore before upgrading"
    [ "$(cw_sha256 "$DIO")" = "$(cw_sha256 "$ROOT/dio_manager.sh")" ] || fail "Installed DIO launcher differs"
    echo "This version is already installed; no changes made"; exit 0
fi
"$TOOL" --check-firmware || fail "Unsupported firmware; nothing changed"
[ "$(cw_sha256 "$DIO")" = '9c1ecb4fb2f9f8d23c40be84daada9391019da2436f684a2e88d607093af46e8' ] || fail "DIO differs from MU1417 stock"
if [ -e "$DIO.cw-stock" ]; then
    [ "$(cw_sha256 "$DIO.cw-stock")" = "$(cw_sha256 "$DIO")" ] || fail "Existing DIO backup differs from restored stock"
fi
if [ -e "$ROOT" ]; then
    [ -s "$ROOT/backup/dio_manager" ] || fail "Incomplete previous backup"
    [ "$(cw_sha256 "$ROOT/backup/dio_manager")" = "$(cw_sha256 "$DIO")" ] || fail "Previous DIO backup differs from restored stock"
fi
BACKUP="$PAYLOAD/../../carplay-backup-$$"
[ "$FIXTURE" -eq 1 ] || mount -uw "${PAYLOAD%/online/carplay}" || fail "SD not writable"
mkdir "$BACKUP" || fail "Cannot create SD backup"
cp -p "$DIO" "$BACKUP/dio_manager" || fail "SD backup failed"
[ "$(cw_sha256 "$DIO")" = "$(cw_sha256 "$BACKUP/dio_manager")" ] || fail "SD backup verification failed"
rw || fail "App volume unavailable"
CHANGED=0
cleanup() {
    CODE=$?
    trap - EXIT HUP INT TERM
    if [ "$CODE" -ne 0 ] && [ "$CHANGED" -eq 1 ]; then
        echo "Installation failed; restoring original launchers"
        cp -p "$BACKUP/dio_manager" "$DIO.cw-rollback" && mv -f "$DIO.cw-rollback" "$DIO"
        rm -f "$ROOT/installed.manifest" "$ROOT/enabled"
    fi
    ro || CODE=1
    exit "$CODE"
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
mkdir -p "$ROOT/backup" || fail "Cannot create installation directory"
cp -p "$BACKUP/dio_manager" "$ROOT/backup/dio_manager" || fail "Cannot retain unit backup"
while IFS=' ' read -r EXPECTED NAME; do cp "$PAYLOAD/$NAME" "$ROOT/$NAME" || fail "Cannot copy $NAME"; done < "$PAYLOAD/payload.manifest"
cp "$PAYLOAD/payload.manifest" "$ROOT/payload.manifest" || fail "Cannot copy manifest"
verify "$ROOT" || fail "Installed payload verification failed"
chmod 755 "$ROOT/porsche-carplay" "$ROOT/dio_manager.sh" || fail "Cannot set executable permissions"
if [ ! -e "$DIO.cw-stock" ]; then cp -p "$DIO" "$DIO.cw-stock" || fail "Cannot retain stock DIO"; fi
CHANGED=1
cp "$ROOT/dio_manager.sh" "$DIO.cw-new" && chmod 755 "$DIO.cw-new" || fail "Cannot stage DIO launcher"
mv -f "$DIO.cw-new" "$DIO" || fail "Cannot install DIO launcher"
cp "$ROOT/payload.manifest" "$ROOT/installed.manifest" && : > "$ROOT/enabled" || fail "Cannot commit installation"
echo "Installed native-only. HMI/Java launcher was not modified. Backups: $BACKUP and $ROOT/backup"
echo "Restart PCM, show the original map in the right display, then connect CarPlay."
echo "Right-display video is validated; confirm route arrows with a real active route."
